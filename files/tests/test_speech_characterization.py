"""Plan 01B checkpoint A0 — characterization of the five TTS text routes, captured from the original implementation.

The goldens under ``files/tests/golden/speech/`` were generated by ``files/dev-tools/speech_characterization.py``
BEFORE the ``scripts/Universal`` -> ``scripts`` relocation (B1). They record, for a fixed set of inputs, what the Edge
direct and folder paths, Kokoro, Chatterbox and Qwen3 do with source text: structure, paragraphs, sentence and
sub-chunk splits, chunks, the strings handed to each engine, the text the pinned Chatterbox wheel receives after ACT's
structural-colon ``punc_norm``, the pause arithmetic, and Qwen3's spans and seeds.

They are text/chunk/seed baselines, not audio: every engine call is a recording fake and nothing is synthesised or
fetched. Any later pure-refactor checkpoint (B1, A1) must leave them byte-identical; a checkpoint that is *meant* to
change text (A5) must regenerate them on purpose, in a reviewed commit, with the Decisions entry that explains why.
"""

from __future__ import annotations

import json
import socket
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(REPO_ROOT / "files" / "dev-tools"))

import speech_characterization as sc  # noqa: E402

pytestmark = pytest.mark.filterwarnings("ignore::DeprecationWarning")


def stored(route: str) -> dict:
    return json.loads(sc.golden_path(route).read_text(encoding="utf-8"))


def fresh(route: str) -> dict:
    return json.loads(sc.to_json(sc.collect(route)))


# --------------------------------------------------------------------------- #
# The goldens themselves
# --------------------------------------------------------------------------- #
def test_every_route_has_a_golden_and_a_manifest():
    assert sc.ROUTES == ("extraction", "edge_direct", "edge_folder", "kokoro", "chatterbox", "qwen3")
    for route in sc.ROUTES:
        data = stored(route)
        assert data["schema"] == sc.SCHEMA and data["route"] == route and data["data"], route
    manifest = json.loads((sc.GOLDEN_DIR / "MANIFEST.json").read_text(encoding="utf-8"))
    assert manifest["routes"] == list(sc.ROUTES) and manifest["inputs"]


def test_the_stored_input_manifest_matches_the_corpus_the_tool_builds():
    manifest = json.loads((sc.GOLDEN_DIR / "MANIFEST.json").read_text(encoding="utf-8"))
    assert manifest["inputs"] == sc.input_manifest()
    assert {"structure", "punctuation", "oversized", "unbroken_token", "qc_difficult_short"} <= set(manifest["inputs"])


@pytest.mark.parametrize("route", sc.ROUTES)
def test_each_route_still_produces_exactly_its_golden(route):
    assert fresh(route) == stored(route), (
        f"the {route} text route no longer matches its A0 characterization; a pure-refactor checkpoint must not "
        "change it, and an intended change must regenerate the goldens in its own reviewed commit")


def test_collection_is_deterministic():
    assert fresh("qwen3") == fresh("qwen3")
    assert fresh("chatterbox") == fresh("chatterbox")


def test_the_goldens_are_small_enough_to_keep_in_the_repository():
    assert sum(p.stat().st_size for p in sc.GOLDEN_DIR.glob("*.json")) < 1_000_000


# --------------------------------------------------------------------------- #
# What the baselines pin down (so a vacuous golden cannot pass)
# --------------------------------------------------------------------------- #
def test_the_baselines_record_the_behaviour_the_plan_depends_on():
    edge = stored("edge_direct")["data"]["inputs"]["structure"]
    assert edge["title"] == "The Lighthouse Log" and edge["author"] == "A. Writer"
    assert edge["chapter_titles"] == ["Chapter One", "blank", "Chapter Two: The Return"]
    assert any(s.startswith("sntnc0.mp3|Chapter One") for s in edge["read_book"]["spoken"]["items"])
    # Edge direct only honours Title:/Author: before the body; a later "Title:" line is spoken.
    assert any("Title: this line is not a header" in s for s in edge["read_book"]["spoken"]["items"])

    kokoro = stored("kokoro")["data"]["inputs"]["structure"]["engine_calls"]["texts"]["items"][0]
    assert "Title:" not in kokoro and "Author:" not in kokoro  # the inline loop drops those lines anywhere
    assert kokoro.startswith("Chapter One\n\nIt was 6:45")

    folder = stored("edge_folder")["data"]["inputs"]["structure"]["convert_single_pdf"]["engine_chunks"]["items"][0]
    assert "Title: The Lighthouse Log" in folder and "# Chapter One" in folder  # Edge folder does no header parsing

    chatterbox = stored("chatterbox")["data"]["inputs"]["punctuation"]
    generated = chatterbox["generate_calls"]["items"]
    patched = chatterbox["after_structural_colon_punc_norm"]["items"]
    assert any("3:1" in g and "6:45" in g and "https://example.com" in g for g in generated)
    assert any("3:1" in p and "6:45" in p and "https://example.com" in p for p in patched)  # structural colons survive
    assert any(g.endswith("Note:") for g in generated) and any(p.endswith("Note,") for p in patched)  # prose colon -> comma

    qwen = stored("qwen3")["data"]
    assert qwen["constants"]["max_chunk_chars"] == 600 and qwen["constants"]["pipeline_revision"] == 1
    assert len(qwen["inputs"]["structure"]["seeds"]["qwen3-aiden"]) == qwen["inputs"]["structure"]["plan_default"]["n"]
    assert qwen["inputs"]["unbroken_token"]["plan_default"]["error"] == "ChunkPlanError"


def test_the_goldens_contain_no_machine_specific_data():
    text = "".join(p.read_text(encoding="utf-8") for p in sc.GOLDEN_DIR.glob("*.json"))
    assert "C:\\\\Users" not in text and "/Users/" not in text and "AppData" not in text and "\\\\Temp\\\\" not in text


# --------------------------------------------------------------------------- #
# The goldens are sensitive: changing any pinned behaviour changes the collected output
# --------------------------------------------------------------------------- #
def test_changing_the_chatterbox_colon_pause_changes_the_baseline(monkeypatch):
    from tts import chatterbox_synth

    monkeypatch.setattr(chatterbox_synth, "COLON_PAUSE_MS", chatterbox_synth.COLON_PAUSE_MS + 25)
    assert fresh("chatterbox") != stored("chatterbox")


def test_changing_the_edge_comma_pause_changes_the_baseline(monkeypatch):
    from tts.epub2tts_edge import epub2tts_edge

    monkeypatch.setattr(epub2tts_edge, "COMMA_PAUSE_MS", epub2tts_edge.COMMA_PAUSE_MS + 1)
    assert fresh("edge_direct") != stored("edge_direct")


def test_changing_the_qwen3_seed_base_changes_the_baseline(monkeypatch):
    from tts import qwen3_synth

    monkeypatch.setattr(qwen3_synth, "SEED_BASE", qwen3_synth.SEED_BASE + 1)
    assert fresh("qwen3") != stored("qwen3")


def test_changing_a_chunk_ceiling_changes_the_baseline(monkeypatch):
    from tts import batch_convert, kokoro_synth

    monkeypatch.setattr(batch_convert, "CHUNK_TARGET", 2000)
    monkeypatch.setattr(kokoro_synth, "split_into_chunks", lambda text, max_chars=2000: [text])
    assert fresh("edge_folder") != stored("edge_folder")
    assert fresh("kokoro") != stored("kokoro")


