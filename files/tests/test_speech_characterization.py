def test_the_tool_refuses_any_network_attempt_while_collecting():
    with sc.no_network():
        with pytest.raises(AssertionError, match="must not open a network connection"):
            socket.create_connection(("127.0.0.1", 9))
        with pytest.raises(AssertionError):
            import edge_tts

            edge_tts.Communicate("x", "en-US-SteffanNeural")


def test_collection_loads_no_speech_model():
    before = {name for name in ("torch", "chatterbox", "kokoro", "qwen_tts") if name in sys.modules}
    fresh("chatterbox")
    fresh("kokoro")
    after = {name for name in ("torch", "chatterbox", "kokoro", "qwen_tts") if name in sys.modules}
    assert after == before
