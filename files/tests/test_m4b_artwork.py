def test_cover_for_reads_only_the_frozen_artwork_value(tmp_path):
    class Plan:
        def __init__(self, artwork):
            self.artwork = artwork
            self.title = "never read"

    source = png(tmp_path / "c.png")
    assert art.cover_for(Plan(None)) is None
    assert art.cover_for(Plan("")) is None
    assert art.cover_for(Plan("   ")) is None
    loaded = art.cover_for(Plan(str(source)))
    assert loaded is not None and loaded.data == source.read_bytes()
    with pytest.raises(ArtworkError):
        art.cover_for(Plan(str(tmp_path / "gone.png")))


