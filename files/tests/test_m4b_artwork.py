def test_loading_writes_nothing_anywhere_near_the_source(tmp_path):
    jpg(tmp_path / "a.jpg")
    png(tmp_path / "nested" / "b.png")
    before = listing(tmp_path)
    hashes = {p: sha(p) for p in tmp_path.rglob("*") if p.is_file()}
    art.load_cover(tmp_path / "a.jpg")
    art.load_cover(tmp_path / "nested" / "b.png")
    assert listing(tmp_path) == before
    assert {p: sha(p) for p in tmp_path.rglob("*") if p.is_file()} == hashes


