"""The shared M4B artwork service — v0.6.4 Phase 1.

``mp3_tools/m4b_artwork.py`` is the one place both M4B tools (Maker and
Metadata Editor) turn a selected image into what an MP4 container's ``covr``
atom carries. The rules are the v0.6.4 plan's (sections 4.6, 5.11, 6.12,
Phase 1):

- which files may be chosen is the shared capability probe's answer, never a
  list of this module's own — JPG/JPEG and PNG always, HEIC/HEIF only where
  ``shared.image_capabilities`` says the machine decodes it;
- JPG/JPEG and PNG are validated by decoding and embedded as the source's own
  bytes with the matching MP4 cover format; a file whose content does not match
  its name is refused rather than mis-tagged;
- HEIC/HEIF is converted **in memory** to PNG, pixel dimensions preserved, and
  no converted file is written anywhere;
- the selected source is read-only: its hash never changes and no sidecar
  appears beside it;
- embedding touches only the ``covr`` atom of the target container — the audio
  stream is not re-encoded.

Decoding, thumbnailing and the chooser filter are the same shared path the MP3
Tool already proved (``mp3_artwork``); what is M4B-specific here is only the
container representation. Nothing here reaches Tk, a thread, a subprocess or a
panel. Fixtures are tiny real images generated by Pillow under ``tmp_path``;
the one real container is a six-second AAC ``.m4a`` built by the project's own
FFmpeg, which is a required tool rather than a reason to skip.
"""

