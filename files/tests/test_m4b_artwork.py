def test_preview_is_an_in_memory_thumbnail_that_changes_nothing(tmp_path):
    source = png(tmp_path / "big.png", size=(400, 300))
    before = sha(source)
    snapshot = listing(tmp_path)
    thumb = art.preview_image(source, (64, 64))
    assert max(thumb.size) <= 64
    assert sha(source) == before
    assert listing(tmp_path) == snapshot
    assert art.load_cover(source).data == source.read_bytes(), "preview scale never leaks"


