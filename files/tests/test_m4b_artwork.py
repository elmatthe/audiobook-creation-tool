def test_embed_cover_writes_only_the_covr_atom_of_a_real_container(tmp_path, m4a):
    from mutagen.mp4 import MP4Cover

    import shutil
    staged = tmp_path / "staged.m4b"
    shutil.copy2(m4a, staged)
    source = jpg(tmp_path / "cover.jpg", size=(32, 20))
    source_before = sha(source)
    audio_before = audio_digest(staged)
    cover = art.load_cover(source)

    art.embed_cover(staged, cover)

    found = covr_of(staged)
    assert len(found) == 1
    assert bytes(found[0]) == source.read_bytes()
    assert found[0].imageformat == MP4Cover.FORMAT_JPEG
    assert audio_digest(staged) == audio_before, "the audio stream was re-encoded"
    assert sha(source) == source_before
    assert sha(m4a) != sha(staged) and covr_of(m4a) == [], "the original is untouched"


def test_embed_cover_replaces_and_then_removes(tmp_path, m4a):
    from mutagen.mp4 import MP4Cover

    import shutil
    staged = tmp_path / "staged.m4b"
    shutil.copy2(m4a, staged)
    art.embed_cover(staged, art.load_cover(jpg(tmp_path / "one.jpg")))
    art.embed_cover(staged, art.load_cover(png(tmp_path / "two.png")))
    found = covr_of(staged)
    assert len(found) == 1 and found[0].imageformat == MP4Cover.FORMAT_PNG
    audio_before = audio_digest(staged)
    art.embed_cover(staged, None)
    assert covr_of(staged) == []
    assert audio_digest(staged) == audio_before


def test_a_heic_cover_lands_in_the_container_as_png(tmp_path, m4a):
    from mutagen.mp4 import MP4Cover

    import shutil
    source = heic(tmp_path / "cover.heic", size=(40, 28))
    staged = tmp_path / "staged.m4b"
    shutil.copy2(m4a, staged)
    snapshot = listing(tmp_path)
    art.embed_cover(staged, art.load_cover(source))
    found = covr_of(staged)
    assert len(found) == 1 and found[0].imageformat == MP4Cover.FORMAT_PNG
    with Image.open(io.BytesIO(bytes(found[0]))) as decoded:
        assert decoded.size == (40, 28)
    assert listing(tmp_path) == snapshot, "no sidecar; only the staged copy changed"


def test_embed_cover_on_a_non_container_is_a_visible_error(tmp_path):
    not_mp4 = tmp_path / "not.m4b"
    not_mp4.write_bytes(b"definitely not an mp4")
