def test_a_jpeg_is_carried_as_its_own_bytes(tmp_path):
    from mutagen.mp4 import MP4Cover

    source = jpg(tmp_path / "cover.jpg", size=(32, 20))
    before = sha(source)
    cover = art.load_cover(source)
    assert isinstance(cover, M4BCover)
    assert cover.data == source.read_bytes()
    assert cover.image_format == MP4Cover.FORMAT_JPEG
    assert (cover.width, cover.height) == (32, 20)
    assert cover.converted is False
    assert cover.source == source
    assert sha(source) == before


def test_a_png_is_carried_as_its_own_bytes(tmp_path):
    from mutagen.mp4 import MP4Cover

    source = png(tmp_path / "cover.png", size=(24, 16))
    cover = art.load_cover(source)
    assert cover.data == source.read_bytes()
    assert cover.image_format == MP4Cover.FORMAT_PNG
    assert (cover.width, cover.height) == (24, 16)
    assert cover.converted is False


def test_a_heic_becomes_an_in_memory_png_cover_of_the_same_size(tmp_path):
    from mutagen.mp4 import MP4Cover

    source = heic(tmp_path / "cover.heic", size=(40, 28))
    before = sha(source)
    snapshot = listing(tmp_path)
    cover = art.load_cover(source)
    assert cover.image_format == MP4Cover.FORMAT_PNG
    assert cover.converted is True
    assert cover.data[:8] == b"\x89PNG\r\n\x1a\n"
    with Image.open(io.BytesIO(cover.data)) as decoded:
        assert decoded.format == "PNG"
        assert decoded.size == (40, 28)
    assert (cover.width, cover.height) == (40, 28)
    assert sha(source) == before, "the source is never touched"
    assert listing(tmp_path) == snapshot, "no converted sidecar appears anywhere"


def test_a_heic_is_refused_where_the_machine_cannot_decode_it(tmp_path, monkeypatch):
    source = tmp_path / "cover.heic"
    source.write_bytes(b"not really")
    monkeypatch.setattr(image_capabilities, "decodable_suffixes",
                        lambda: image_capabilities.BASELINE_SUFFIXES)
    with pytest.raises(ArtworkError) as refused:
        art.load_cover(source)
    assert "HEIC" in str(refused.value) or ".heic" in str(refused.value)
    assert listing(tmp_path) == {"cover.heic"}


def test_a_mislabelled_image_is_refused_rather_than_mistagged(tmp_path):
    real_png = png(tmp_path / "real.png")
    lying = tmp_path / "lying.jpg"
    lying.write_bytes(real_png.read_bytes())
    before = sha(lying)
    with pytest.raises(ArtworkError):
        art.load_cover(lying)
    assert sha(lying) == before


