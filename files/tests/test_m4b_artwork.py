def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def png(path: Path, size=(24, 16)) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    Image.new("RGB", size, (200, 30, 30)).save(path, format="PNG")
    return path


def jpg(path: Path, size=(32, 20)) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    Image.new("RGB", size, (30, 200, 30)).save(path, format="JPEG", quality=90)
    return path


def heic(path: Path, size=(40, 28)) -> Path:
    capability = image_capabilities.heif_capability()
    if not capability.decode:
        pytest.skip(f"this machine cannot decode HEIC/HEIF: {capability.detail}")
    if not capability.encode:
        pytest.skip(f"this machine cannot write a HEIC fixture: {capability.detail}")
    path.parent.mkdir(parents=True, exist_ok=True)
    Image.new("RGB", size, (30, 30, 200)).save(path, format=image_capabilities.HEIF_FORMAT)
    return path


def listing(root: Path) -> set[str]:
    return {p.relative_to(root).as_posix() for p in root.rglob("*")}


def require_ffmpeg() -> str:
    """FFmpeg is a required tool: an unresolvable binary is a failure, not a skip."""
    if not ffmpeg_utils.have_ffmpeg():
        pytest.fail("ffmpeg/ffprobe could not be resolved, so the real-container "
                    f"cases cannot run: ffmpeg_path()={ffmpeg_utils.ffmpeg_path()!r}")
    return ffmpeg_utils.ffmpeg_cmd()


def _ff(*args) -> bytes:
    out = subprocess.run([ffmpeg_utils.ffmpeg_cmd(), "-hide_banner", "-v", "error", "-y", *args],
                         stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    assert out.returncode == 0, out.stdout.decode("utf-8", "replace")[-800:]
    return out.stdout


def audio_digest(path: Path) -> str:
    """MD5 of the packed audio stream, copied without re-encoding.

    Two files whose audio was not touched give the same digest; a re-encode
    cannot.
    """
    out = _ff("-i", str(path), "-map", "0:a", "-c", "copy", "-f", "md5", "-")
    return out.decode("ascii", "replace").strip()


@pytest.fixture(scope="module")
def m4a(tmp_path_factory) -> Path:
    require_ffmpeg()
    work = tmp_path_factory.mktemp("m4b_artwork")
    target = work / "book.m4a"
    _ff("-f", "lavfi", "-i", "sine=frequency=440:duration=6", "-c:a", "aac",
        "-b:a", "64k", str(target))
    return target


def covr_of(path: Path) -> list:
    from mutagen.mp4 import MP4
    tags = MP4(str(path)).tags
    return list(tags.get("covr", [])) if tags else []


