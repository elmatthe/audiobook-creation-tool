"""The multi-Book Write ID3 pipeline — v0.6.3 focused MP3 plan, Phase 7.

``mp3_tools/mp3_processing.py`` runs one frozen Phase 5 ``RunPlan`` for the
Write ID3 Tags operation: every track becomes a **new clean staged copy** with the
frozen signed Time applied, then carries exactly the whitelisted ID3 frames the
plan intends (Title, Artist / Album Artist / Album when populated, Track Number
when Auto-number is on, one front cover from the Phase 6 artwork service), and
a Book is published only when every track staged and validated. A failed Book
publishes nothing; its successful pieces stay in private staging for the later
exact failed-item retry; later Books still run.

Real media, deliberately: sources are one-second tones generated by the pinned
FFmpeg under ``tmp_path`` and tagged with junk frames by mutagen. Nothing here
opens a controller, a thread, a widget or Combine.
"""

