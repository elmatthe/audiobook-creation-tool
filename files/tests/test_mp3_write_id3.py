def test_a_book_publishes_only_after_every_track_succeeds(sources, reserve, monkeypatch):
    made, entry = one_book_plan(sources, reserve, names=("01.mp3", "02.mp3", "03.mp3"), title="")
    seen: list[str] = []
    real = mp.publish_book

    def spy(book_plan):
        seen.append("publish")
        for path in book_plan.staged_outputs:
            assert path.is_file(), "every track is staged before publication"
        assert not book_plan.published_dir.exists()
        return real(book_plan)

    monkeypatch.setattr(proc.mp3_plan, "publish_book", spy)
    report = proc.write_id3_run(made)
    assert seen == ["publish"]
    assert report.books[0].succeeded
    assert sorted(p.name for p in made.books[0].published_dir.iterdir()) == [
        "01 01.mp3", "02 02.mp3", "03 03.mp3"]
    assert not made.books[0].staging_dir.exists() or not any(made.books[0].staging_dir.iterdir())


def test_a_fails_b_fails_c_succeeds_leaves_a_and_c_published_and_b_private(sources, reserve):
    a = book([imported(sources, "A", "1.mp3"), imported(sources, "A", "2.mp3")], album="A")
    bad = imported(sources, "B", "2.mp3", junk=False)
    bad.path.write_bytes(b"this is not an mp3 at all")
    b = book([imported(sources, "B", "1.mp3"), bad, imported(sources, "B", "3.mp3")], album="B")
    c = book([imported(sources, "C", "1.mp3")], album="C")
    made = plan(workspace(a, b, c), observe(a, b, c), reserve)
    report = proc.write_id3_run(made)

    ra, rb, rc = report.books
    assert ra.succeeded and rc.succeeded and not rb.succeeded
    assert made.books[0].published_dir.is_dir() and made.books[2].published_dir.is_dir()
    assert not made.books[1].published_dir.exists(), "B publishes nothing"
    assert [r.result.state for r in report.books] == [
        JobState.SUCCEEDED, JobState.COMPLETED_WITH_FAILURES, JobState.SUCCEEDED]

    # B's failure names the real occurrence; the other two staged pieces survive.
    record, = rb.result.failures.records
    assert record.item_id == bad.occurrence_id
    assert record.retryable is True
    assert rb.result.retryable_ids == (bad.occurrence_id,)
    survivors = [t for t in made.books[1].tracks if t.occurrence_id != bad.occurrence_id]
    assert all(t.staged.is_file() for t in survivors), "kept for the exact failed-item retry"
    assert not made.books[1].track_for(bad.occurrence_id).staged.exists()
    assert set(rb.result.completed_ids) == {t.occurrence_id for t in survivors}
    assert rb.staged_ok == tuple(t.occurrence_id for t in survivors)
    # The retry request Plan 7 derives is the failed subset against the same snapshot.
    request = rb.result.retry()
    assert request.item_ids == (bad.occurrence_id,)
    assert request.snapshot is made.books[1].snapshot
    assert report.failed_book_ids == (b.book_id,)


