    proc.write_id3_run(made)
    for track, expected_title, number in zip(made.books[0].tracks, ("First", "Second"), (1, 2)):
        out = track.published
        assert set(frames(out)) == {"TIT2", "TPE1", "TPE2", "TALB", "TRCK"}
        text = texts(out)
        assert text["TIT2"] == expected_title
        assert text["TPE1"] == "New Artist"
        assert text["TPE2"] == "New Narrator"
        assert text["TALB"] == "New Album"
        assert text["TRCK"] == str(number), "an ordinary integer, not display-padded"
        assert set(frames(out)) <= WHITELIST
        for junk in ("TYER", "TCON", "TCOM", "COMM", "TXXX", "APIC"):
            assert junk not in frames(out), junk


