def test_zero_time_still_creates_a_distinct_clean_output(sources, reserve):
    made, entry = one_book_plan(sources, reserve)
    source = entry.files.files[0].path
    before = sha(source)
    report = proc.write_id3_run(made)
    assert isinstance(report, WriteId3Report)
    track = made.books[0].tracks[0]
    assert track.published.is_file()
    assert track.published != source
    assert sha(source) == before, "the source is read-only"
    assert sha(track.published) != before, "a new clean file, not a copy of the bytes"
    assert abs(duration(track.published) - duration(source)) < 0.15
    assert report.books[0].succeeded


def test_positive_time_appends_to_the_end(sources, reserve):
    made, entry = one_book_plan(sources, reserve, time_delta="1.5")
    source = entry.files.files[0].path
    proc.write_id3_run(made)
    out = made.books[0].tracks[0].published
    assert abs(duration(out) - (duration(source) + 1.5)) < 0.2
    assert made.books[0].time_delta == 1.5


def test_negative_time_trims_from_the_end(sources, reserve):
    files = [imported(sources, "Book", "01.mp3", seconds=3.0)]
    entry = book(files, time_delta="-1")
    made = plan(workspace(entry), observe(entry), reserve)
    proc.write_id3_run(made)
    out = made.books[0].tracks[0].published
    assert abs(duration(out) - (duration(files[0].path) - 1.0)) < 0.2


def test_an_excessive_trim_fails_safely_with_the_real_occurrence(sources, reserve):
    files = [imported(sources, "Book", "01.mp3", seconds=1.0),
             imported(sources, "Book", "02.mp3", seconds=1.0)]
    entry = book(files, time_delta="-5")
    made = plan(workspace(entry), observe(entry), reserve)
    report = proc.write_id3_run(made)
    result = report.books[0]
    assert result.succeeded is False
    assert not made.books[0].published_dir.exists(), "no partial Book is visible"
    assert not any(t.published.exists() for t in made.books[0].tracks)
    failures = result.result.failures.records
    assert {f.item_id for f in failures} == {f.occurrence_id for f in files}
    for record in failures:
        assert isinstance(record, FailureRecord)
        assert record.retryable is True
        assert "trim" in record.display_message.lower()
        assert record.snapshot_id == made.books[0].snapshot.snapshot_id
    assert not any(t.staged.exists() for t in made.books[0].tracks), (
        "no invalid or zero-length output was manufactured")
    assert result.result.state is JobState.COMPLETED_WITH_FAILURES


