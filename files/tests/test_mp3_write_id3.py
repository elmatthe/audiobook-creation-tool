def tone(path: Path, seconds: float = 1.0, freq: int = 440) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    sp.run([ffmpeg_utils.ffmpeg_cmd(), "-hide_banner", "-loglevel", "error", "-y",
            "-f", "lavfi", "-i", f"sine=frequency={freq}:duration={seconds}",
            "-ac", "2", "-ar", "44100", "-c:a", "libmp3lame", "-b:a", "64k", str(path)],
           check=True)
    return path


def junk_tag(path: Path, *, title="Old Title", artist="Old Artist", album="Old Album",
             with_art=True) -> Path:
    tags = ID3()
    tags.add(TIT2(encoding=3, text=[title]))
    tags.add(TPE1(encoding=3, text=[artist]))
    tags.add(TALB(encoding=3, text=[album]))
    tags.add(TRCK(encoding=3, text=["77"]))
    tags.add(TYER(encoding=3, text=["1999"]))
    tags.add(TCON(encoding=3, text=["Speech"]))
    tags.add(TCOM(encoding=3, text=["Old Composer"]))
    tags.add(COMM(encoding=3, lang="eng", desc="", text=["old comment"]))
    tags.add(TXXX(encoding=3, desc="custom", text=["x"]))
    if with_art:
        tags.add(APIC(encoding=3, mime="image/jpeg", type=3, desc="old", data=b"old-art"))
    tags.save(path, v2_version=3)
    return path


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def duration(path: Path) -> float:
    value = proc.ffprobe_duration_seconds(path)
    assert value is not None, path
    return value


def frames(path: Path) -> dict[str, object]:
    try:
        tags = ID3(path)
    except Exception:
        return {}
    return {key.split(":")[0]: frame for key, frame in tags.items()}


def texts(path: Path) -> dict[str, str]:
    return {key: "/".join(str(t) for t in frame.text)
            for key, frame in frames(path).items() if hasattr(frame, "text")}


def png(path: Path, size=(24, 16)) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    Image.new("RGB", size, (200, 30, 30)).save(path, format="PNG")
    return path


def jpg(path: Path, size=(32, 20)) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    Image.new("RGB", size, (30, 200, 30)).save(path, format="JPEG", quality=90)
    return path


@pytest.fixture
def sources(tmp_path: Path) -> Path:
    root = tmp_path / "Sources"
    root.mkdir()
    return root


@pytest.fixture
def reserve(tmp_path: Path):
    counter = {"n": 0}

    def make(tool_key="mp3_tool", **_kw):
        counter["n"] += 1
        directory = tmp_path / "Outputs" / f"MP3-Tool-{counter['n']}"
        directory.mkdir(parents=True)
        return output_paths.RunReservation(
            tool_key=tool_key, base_directory=tmp_path / "Outputs",
            tool_directory=tmp_path / "Outputs", run_directory=directory,
            run_number=counter["n"])

    make.calls = counter  # type: ignore[attr-defined]
    return make


def imported(sources: Path, folder: str, name: str, *, seconds=1.0, freq=440,
             junk=True, with_art=True, title="Old Title") -> ImportedFile:
    path = tone(sources / folder / name, seconds=seconds, freq=freq)
    if junk:
        junk_tag(path, with_art=with_art, title=title)
    occurrence = _IDS.next_id("occurrence")
    return ImportedFile(occurrence, path, ImportRoot("r", sources, 0),
                        PurePath(folder) / name, "mp3", f"id-{occurrence}")


def book(files, **configuration) -> BookJob:
    return BookJob(book_id=book_workspace.new_book_id(_IDS), configuration=configuration,
                   files=ImportedFileSnapshot(Revision(1), tuple(files)))


def workspace(*books: BookJob, shared: SharedMetadata | None = None) -> WorkspaceSnapshot:
    return WorkspaceSnapshot(
        books=books, current_book_id=books[0].book_id,
        shared=wf.new_shared_metadata() if shared is None else shared)


def observe(*books: BookJob) -> wf.ObservationStore:
    store = wf.ObservationStore()
    for entry in books:
        store = store.with_observations(wf.observe_files(entry.files.files))
    return store


def plan(space, store, reserve, **kwargs) -> mp.RunPlan:
    return mp.plan_run(
        space, store, operation=mp.MP3Operation.WRITE_ID3, reservation=reserve(),
        catalog=wf.MP3_CATALOG, import_options=ImportOptions.for_catalog(wf.MP3_CATALOG),
        effective_config=make_config(), id_factory=_IDS, **kwargs)


def one_book_plan(sources, reserve, names=("01 One.mp3",), title="Old Title", **configuration):
    files = [imported(sources, "Book", name, title=title) for name in names]
    entry = book(files, **configuration)
    return plan(workspace(entry), observe(entry), reserve), entry


