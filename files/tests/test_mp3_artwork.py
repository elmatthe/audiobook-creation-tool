def test_a_mislabelled_image_is_refused_rather_than_mistagged(tmp_path):
    """A PNG saved as ``.jpg`` would be embedded with the wrong MIME; refuse it."""
    disguised = png(tmp_path / "actually.png")
    renamed = tmp_path / "actually.jpg"
    disguised.rename(renamed)
    with pytest.raises(ArtworkError):
        art.load_artwork(renamed)


def test_an_unsupported_suffix_or_missing_file_is_an_artwork_error(tmp_path):
    (tmp_path / "cover.gif").write_bytes(b"GIF89a")
    with pytest.raises(ArtworkError):
        art.load_artwork(tmp_path / "cover.gif")
    with pytest.raises(ArtworkError):
        art.load_artwork(tmp_path / "missing.png")
    with pytest.raises(ArtworkError):
        art.load_artwork("")


def test_loading_leaves_no_temporary_file_behind(tmp_path):
    jpg(tmp_path / "a.jpg")
    png(tmp_path / "b.png")
    before = listing(tmp_path)
    art.load_artwork(tmp_path / "a.jpg")
    art.load_artwork(tmp_path / "b.png")
    assert listing(tmp_path) == before


