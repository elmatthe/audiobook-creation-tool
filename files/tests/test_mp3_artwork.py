def test_preview_is_an_in_memory_thumbnail_that_changes_nothing(tmp_path):
    source = jpg(tmp_path / "big.jpg", size=(300, 200))
    before = sha(source)
    snapshot = listing(tmp_path)
    preview = art.preview_image(source, (56, 56))
    assert isinstance(preview, Image.Image)
    assert max(preview.size) <= 56
    assert preview.size == (56, 37)
    assert sha(source) == before
    assert listing(tmp_path) == snapshot
    loaded = art.load_artwork(source)
    assert (loaded.width, loaded.height) == (300, 200), "the tag gets the full image"
    assert loaded.data == source.read_bytes()


def test_preview_of_a_heic_uses_the_same_capability_gate(tmp_path):
    source = heic(tmp_path / "cover.heic", size=(90, 60))
    preview = art.preview_image(source, (30, 30))
    assert preview.size == (30, 20)


