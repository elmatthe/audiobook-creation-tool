"""The MP3 artwork / APIC service — v0.6.3 focused MP3 plan, Phase 6.

``mp3_tools/mp3_artwork.py`` is the one place the MP3 Tool turns a selected
image into what an ID3 tag carries. JPG/JPEG and PNG are embedded as the
source's own bytes; HEIC/HEIF is decoded through the shared capability path and
converted to PNG **in memory** for the tag only. Nothing here resizes, crops or
rewrites a source, and nothing writes an MP3 — the Write ID3 / Combine pipelines
apply the frame later, from the frozen ``BookPlan.artwork`` value.

Fixtures are small real images generated by Pillow under ``tmp_path``. HEIC
tests are gated on the shared capability probe, exactly as the chooser is.
"""

from __future__ import annotations

import ast
import hashlib
import io
from pathlib import Path, PurePath

import pytest
from PIL import Image

from shared import image_capabilities

from mp3_tools import mp3_artwork as art
from mp3_tools import mp3_plan as mp
from mp3_tools.mp3_artwork import Artwork, ArtworkError

REPO_ROOT = Path(__file__).resolve().parents[2]
UNIVERSAL = REPO_ROOT / "scripts" / "Universal"
MODULE = UNIVERSAL / "mp3_tools" / "mp3_artwork.py"


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def png(path: Path, size=(24, 16)) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    Image.new("RGB", size, (200, 30, 30)).save(path, format="PNG")
    return path


def jpg(path: Path, size=(32, 20)) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    Image.new("RGB", size, (30, 200, 30)).save(path, format="JPEG", quality=90)
    return path


def heic(path: Path, size=(40, 28)) -> Path:
    capability = image_capabilities.heif_capability()
    if not capability.decode:
        pytest.skip(f"this machine cannot decode HEIC/HEIF: {capability.detail}")
    if not capability.encode:
        pytest.skip(f"this machine cannot write a HEIC fixture: {capability.detail}")
    path.parent.mkdir(parents=True, exist_ok=True)
    Image.new("RGB", size, (30, 30, 200)).save(path, format=image_capabilities.HEIF_FORMAT)
    return path


def listing(root: Path) -> set[str]:
    return {p.relative_to(root).as_posix() for p in root.rglob("*")}


