def apic_frames(tags):
    return [frame for frame in tags.values() if frame.FrameID == "APIC"]


def test_the_frame_is_one_front_cover_with_the_exact_bytes(tmp_path):
    from mutagen.id3 import ID3, PictureType

    source = png(tmp_path / "cover.png")
    loaded = art.load_artwork(source)
    tags = ID3()
    art.apply_artwork(tags, loaded)
    frames = apic_frames(tags)
    assert len(frames) == 1
    frame = frames[0]
    assert frame.type == PictureType.COVER_FRONT
    assert int(frame.type) == 3
    assert frame.mime == "image/png"
    assert frame.data == source.read_bytes()
    with Image.open(io.BytesIO(frame.data)) as embedded:
        assert embedded.size == (24, 16)


def test_old_artwork_never_survives_the_intended_state(tmp_path):
    from mutagen.id3 import APIC, ID3

    tags = ID3()
    tags.add(APIC(encoding=3, mime="image/jpeg", type=3, desc="old", data=b"old front"))
    tags.add(APIC(encoding=3, mime="image/jpeg", type=4, desc="back", data=b"old back"))
    assert len(apic_frames(tags)) == 2

    # Intended: a new front cover -> exactly that one, nothing old.
    loaded = art.load_artwork(jpg(tmp_path / "new.jpg"))
    art.apply_artwork(tags, loaded)
    frames = apic_frames(tags)
    assert len(frames) == 1 and frames[0].data == loaded.data

    # Intended: no artwork -> no APIC at all.
    art.apply_artwork(tags, None)
    assert apic_frames(tags) == []


def test_no_artwork_means_no_apic_on_a_fresh_tag():
    from mutagen.id3 import ID3

    tags = ID3()
    art.apply_artwork(tags, None)
    assert apic_frames(tags) == []


def test_applying_twice_still_leaves_exactly_one_frame(tmp_path):
    from mutagen.id3 import ID3

    tags = ID3()
    first = art.load_artwork(png(tmp_path / "a.png"))
    second = art.load_artwork(jpg(tmp_path / "b.jpg"))
    art.apply_artwork(tags, first)
    art.apply_artwork(tags, second)
    frames = apic_frames(tags)
    assert len(frames) == 1
    assert frames[0].mime == "image/jpeg" and frames[0].data == second.data


def test_the_frame_round_trips_through_a_real_id3_write(tmp_path):
    """The one place a file is written here, and it is a test-owned stub."""
    from mutagen.id3 import ID3

    source = jpg(tmp_path / "cover.jpg")
    stub = tmp_path / "track.mp3"
    stub.write_bytes(b"\x00" * 64)
    tags = ID3()
    art.apply_artwork(tags, art.load_artwork(source))
    tags.save(stub)
    read_back = apic_frames(ID3(stub))
    assert len(read_back) == 1
    assert read_back[0].data == source.read_bytes()
    assert read_back[0].mime == "image/jpeg" and int(read_back[0].type) == 3


def test_a_heic_frame_is_png_bytes_with_preserved_dimensions(tmp_path):
    from mutagen.id3 import ID3

    source = heic(tmp_path / "cover.heic", size=(40, 28))
    tags = ID3()
    art.apply_artwork(tags, art.load_artwork(source))
    frame, = apic_frames(tags)
    assert frame.mime == "image/png"
    with Image.open(io.BytesIO(frame.data)) as embedded:
        assert embedded.format == "PNG" and embedded.size == (40, 28)
    assert not (tmp_path / "cover.png").exists()


