def test_the_chooser_filter_derives_from_the_shared_capability():
    types = art.artwork_filetypes()
    patterns = types[0][1].split()
    assert patterns == [f"*{s}" for s in image_capabilities.decodable_suffixes()]
    assert types[-1] == ("All files", "*.*")


def test_the_service_declares_no_capability_list_of_its_own():
    tree = ast.parse(MODULE.read_text(encoding="utf-8"))
    literals = {node.value for node in ast.walk(tree)
                if isinstance(node, ast.Constant) and isinstance(node.value, str)}
    for suffix in (".heic", ".heif", ".jpg", ".jpeg", ".png"):
        assert suffix not in literals, f"{suffix} is the shared probe's to know"
    modules = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            modules |= {alias.name for alias in node.names}
        elif isinstance(node, ast.ImportFrom):
            modules.add(node.module or "")
            modules |= {f"{node.module}.{alias.name}" for alias in node.names}
    assert "pillow_heif" not in modules, "the optional import belongs to the shared probe"
    assert "shared.image_capabilities" in modules
    for banned in ("tkinter", "subprocess", "threading", "shutil", "shared.ffmpeg_utils",
                   "shared.job_ui", "shared.output_paths", "mp3_tools.mp3_tool"):
        assert banned not in modules, banned


