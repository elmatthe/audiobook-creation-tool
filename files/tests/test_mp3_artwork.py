def test_artwork_is_loaded_from_the_frozen_book_plan_value(tmp_path):
    from shared import book_workspace, output_paths
    from shared.importing import (IdFactory, ImportOptions, ImportedFile,
                                  ImportedFileSnapshot, ImportRoot, Revision)
    from mp3_tools import mp3_workflow as wf
    from test_importing import make_config

    ids = IdFactory("art-")
    source = tmp_path / "Sources" / "Book" / "1.mp3"
    source.parent.mkdir(parents=True)
    source.write_bytes(b"x")
    cover = png(tmp_path / "cover.png")
    entry = ImportedFile(ids.next_id("occurrence"), source,
                         ImportRoot("r", tmp_path / "Sources", 0), PurePath("Book/1.mp3"),
                         "mp3", "id-1")
    book = book_workspace.BookJob(
        book_id=book_workspace.new_book_id(ids), configuration={"artwork": str(cover)},
        files=ImportedFileSnapshot(Revision(1), (entry,)))
    space = book_workspace.WorkspaceSnapshot(
        books=(book,), current_book_id=book.book_id, shared=wf.new_shared_metadata())
    run = tmp_path / "Outputs" / "MP3-Tool-1"
    run.mkdir(parents=True)
    reservation = output_paths.RunReservation(
        tool_key="mp3_tool", base_directory=tmp_path / "Outputs",
        tool_directory=tmp_path / "Outputs", run_directory=run, run_number=1)
    store = wf.ObservationStore().with_observations(
        wf.observe_files((entry,), reader=lambda p: wf.SourceTags()))
    plan = mp.plan_run(space, store, operation=mp.MP3Operation.WRITE_ID3,
                       reservation=reservation, catalog=wf.MP3_CATALOG,
                       import_options=ImportOptions.for_catalog(wf.MP3_CATALOG),
                       effective_config=make_config(), id_factory=ids)
    frozen = plan.books[0]
    assert frozen.artwork == cover
    loaded = art.artwork_for(frozen)
    assert loaded is not None and loaded.data == cover.read_bytes()

    # The plan value is what counts: replacing the file afterwards is a
    # different image, and a later load honestly reports the *current* bytes
    # of the frozen path -- the panel's live widgets are never consulted.
    none_plan = mp.BookPlan(**{**{f: getattr(frozen, f) for f in frozen.__dataclass_fields__},
                               "artwork": None})
    assert art.artwork_for(none_plan) is None


